import streamlit as st

st.set_page_config(page_title="피싱 예방법 & 퀴즈", page_icon="📚")

st.title("📚 피싱 예방 가이드 & 모의 퀴즈")
st.write("최신 피싱 수법을 학습하고 퀴즈를 통해 피싱 대처 능력을 키워보세요!")

st.divider()

# --- Section 1: 피싱 유형별 대응 가이드 ---
st.subheader("💡 최신 피싱/스미싱 대표 수법")

with st.expander("1. ⚖️ 검찰/금융감독원 사칭"):
    st.write("""
    - **수법:** "귀하의 계좌가 범죄에 봉착했습니다", "안전계좌로 이체하세요" 등의 문자로 위협.
    - **대처법:** 수사기관이나 금융기관은 **절대 전화나 문자로 돈 이체나 개인정보를 요구하지 않습니다.** 즉시 끊고 112로 확인하세요.
    """)

with st.expander("2. 📦 택배 배송 오류 / 모바일 청첩장"):
    st.write("""
    - **수법:** "주소지 불명으로 배송 중단", "모바일 청첩장이 도착했습니다" 문자에 링크(.apk) 첨부.
    - **대처법:** 문자에 포함된 **URL 링크를 절대로 누르지 마세요.** 누르는 순간 악성 앱이 설치되어 핸드폰이 원격 제어될 수 있습니다.
    """)

with st.expander("3. 💸 가족/지인 사칭 (고수익 알바, 급전 요구)"):
    st.write("""
    - **수법:** "엄마 나 액정 깨져서 부캐로 문자했어", "상품권 구매 대행 알바" 등.
    - **대처법:** 반드시 **기존에 저장된 전화번호로 직접 전화**를 걸어 본인인지 확인해야 합니다.
    """)

st.divider()

# --- Section 2: 피싱 대처 능력 모의 테스트 ---
st.subheader("🧩 피싱 대처 능력 모의 퀴즈")
st.write("아래 문자를 받았을 때 올바른 행동을 선택해 보세요.")

# 퀴즈 1
st.markdown("---")
st.markdown("**Q1. [WEB발신] '고객님의 택배가 배송 주소 불명으로 보관 중입니다. 아래 링크에서 주소를 수정하세요: http://bit.ly/3x8f.apk' 문자를 받았습니다. 어떻게 해야 할까요?**")

q1_answer = st.radio(
    "정답을 선택하세요:",
    ["① 링크를 눌러 주소를 수정한다.", "② 첨부된 .apk 파일을 다운로드한다.", "③ 링크를 절대 누르지 않고 문자를 삭제하거나 택배사 공식 앱에서 확인한다."],
    key="q1"
)

if st.button("Q1 정답 확인"):
    if q1_answer.startswith("③"):
        st.success("🎉 정답입니다! 문자에 포함된 .apk 파일은 악성 앱 설치 파일일 확률이 높으므로 절대 누르면 안 됩니다.")
    else:
        st.error("❌ 오답입니다! 출처가 불분명한 문자 내 링크는 악성 앱 설치로 이어질 수 있습니다.")

# 퀴즈 2
st.markdown("---")
st.markdown("**Q2. 검찰청 수사관이라는 사람에게 전화가 와서 '명의도용 사건에 연루되었으니 자산을 안전계좌로 옮기라'고 합니다. 올바른 대처법은?**")

q2_answer = st.radio(
    "정답을 선택하세요:",
    ["① 즉시 지시받은 안전계좌로 돈을 이체한다.", "② 전화를 끊고 112(경찰청)나 해당 기관의 공식 대표번호로 직접 전화하여 확인한다.", "③ 상대방에게 내 주민등록번호와 계좌 비밀번호를 알려준다."],
    key="q2"
)

if st.button("Q2 정답 확인"):
    if q2_answer.startswith("②"):
        st.success("🎉 정답입니다! 어떤 국가기관도 전화나 문자로 돈의 이체나 개인정보를 요구하지 않습니다.")
    else:
        st.error("❌ 오답입니다! 검찰이나 금감원은 절대 개인 계좌 이체를 요구하지 않습니다.")
